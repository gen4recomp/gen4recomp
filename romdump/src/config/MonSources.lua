-- Pseudo personal/learnset member bases for ResolveMonForm (src/pokemon.c):
-- a nonzero form of these species reads the pseudo member, all base forms
-- are form value 0.
local FORM_PERSONAL_BASES = {
  [386] = 496, -- DEOXYS
  [413] = 499, -- WORMADAM
  [487] = 501, -- GIRATINA
  [492] = 502, -- SHAYMIN
  [479] = 503, -- ROTOM
}

-- Form clamp ported from sub_02070438 (src/pokemon.c). Out-of-range forms
-- fall back to 0 exactly as the source does.
function MonSources.clampForm(speciesId, form)
  assert(type(speciesId) == "number" and type(form) == "number", "clampForm requires ids")
  local max = MonSources.formMaxes[speciesId]
  if max == nil then
    return form
  end
  if speciesId == MonSources.speciesId("UNOWN") then
    if form >= max then
      return 0
    end
    return form
  end
  if form > max - 1 then
    return 0
  end
  return form
end

-- Runtime form values for a species id: 0..max-1 for form species, else {0}.
function MonSources.runtimeForms(speciesId)
  local max = MonSources.formMaxes[speciesId] or 1
  local forms = {}
  for form = 0, max - 1 do
    forms[#forms + 1] = form
  end
  return forms
end

-- Personal/learnset member resolution ported from ResolveMonForm
-- (src/pokemon.c). Evolution members resolve by plain species id
-- (LoadMonEvolutionTable); the pseudo evo members are byte-identical to
-- their base members on supported dumps.
function MonSources.resolvePersonalMember(speciesId, form)
  local pseudo = FORM_PERSONAL_BASES[speciesId]
  if pseudo ~= nil and form ~= 0 then
    return pseudo + form - 1
  end
  return speciesId
end

-- Party-icon member ported from GetMonIconNaixEx (src/pokemon_icon_idx.c).
-- isEgg selects the egg members (Manaphy eggs use 502, all others 501).
function MonSources.iconNaix(speciesId, isEgg, form)
  local SPECIES_MANAPHY = speciesIds["MANAPHY"]
  if isEgg then
    if speciesId == SPECIES_MANAPHY then
      return 502
    end
    return 501
  end
  form = MonSources.clampForm(speciesId, form)
  if form ~= 0 then
    if speciesId == speciesIds["DEOXYS"] then
      return form + 503 - 1
    elseif speciesId == speciesIds["UNOWN"] then
      return form + 507 - 1
    elseif speciesId == speciesIds["BURMY"] then
      return form + 534 - 1
    elseif speciesId == speciesIds["WORMADAM"] then
      return form + 536 - 1
    elseif speciesId == speciesIds["SHELLOS"] then
      return form + 538 - 1
    elseif speciesId == speciesIds["GASTRODON"] then
      return form + 539 - 1
    elseif speciesId == speciesIds["GIRATINA"] then
      return form + 540 - 1
    elseif speciesId == speciesIds["SHAYMIN"] then
      return form + 541 - 1
    elseif speciesId == speciesIds["ROTOM"] then
      return form + 542 - 1
    end
  end
  if speciesId > MonSources.MAX_SPECIES then
    speciesId = 0
  end
  return speciesId + 7
end

-- Party-icon palette ported from GetMonIconPaletteEx
-- (src/pokemon_icon_idx.c): the computed slot indexes iconPalettes.
function MonSources.iconPalette(speciesId, form, isEgg)
  local slot = speciesId
  if isEgg then
    if speciesId == speciesIds["MANAPHY"] then
      slot = 495
    else
      slot = 494
    end
  elseif speciesId > MonSources.MAX_SPECIES then
    slot = 0
  elseif form ~= 0 then
    if speciesId == speciesIds["DEOXYS"] then
      slot = 496 + form - 1
    elseif speciesId == speciesIds["UNOWN"] then
      slot = 499 + form - 1
    elseif speciesId == speciesIds["BURMY"] then
      slot = 527 + form - 1
    elseif speciesId == speciesIds["WORMADAM"] then
      slot = 529 + form - 1
    elseif speciesId == speciesIds["SHELLOS"] then
      slot = 531 + form - 1
    elseif speciesId == speciesIds["GASTRODON"] then
      slot = 532 + form - 1
    elseif speciesId == speciesIds["GIRATINA"] then
      slot = 533 + form - 1
    elseif speciesId == speciesIds["SHAYMIN"] then
      slot = 534 + form - 1
    elseif speciesId == speciesIds["ROTOM"] then
      slot = 535 + form - 1
    end
  end
  local palette = MonSources.iconPalettes[slot]
  assert(palette ~= nil, "icon palette slot out of range: " .. tostring(slot))
  return palette
end

-- Front-portrait character/palette member selection ported from
-- GetMonSpriteCharAndPlttNarcIdsEx (src/pokemon.c). gender is "male" or "female"; facing is 0 (back) or 2 (front); shiny is boolean. Returns the source NARC alias plus char/pal
-- member ids. The default (base-species) branch and the otherpoke branch
-- mirror the source switch exactly, including the shared Deoxys/Unown
-- palettes and the egg members.
function MonSources.portraitIds(speciesId, gender, facing, shiny, form)
  assert(gender == "male" or gender == "female", "portrait gender must be male or female")
  assert(facing == 0 or facing == 2, "portrait facing must be 0 (back) or 2 (front)")
  local isFemale = gender == "female"
  local shinyBit = shiny and 1 or 0
  local halfFacing = math.floor(facing / 2)
  form = MonSources.clampForm(speciesId, form)
  local function otherpoke(charId, palId)
    return { narc = "pokemon_graphics_other", charMemberId = charId, palMemberId = palId }
  end
  if speciesId == speciesIds["BURMY"] then
    return otherpoke(halfFacing + 0x48 + form * 2, shinyBit + 0xAA + form * 2)
  elseif speciesId == speciesIds["WORMADAM"] then
    return otherpoke(halfFacing + 0x4E + form * 2, shinyBit + 0xB0 + form * 2)
  elseif speciesId == speciesIds["SHELLOS"] then
    return otherpoke(facing + 0x54 + form, shinyBit + 0xB6 + form * 2)
  elseif speciesId == speciesIds["GASTRODON"] then
    return otherpoke(facing + 0x58 + form, shinyBit + 0xBA + form * 2)
  elseif speciesId == speciesIds["CHERRIM"] then
    return otherpoke(facing + 0x5C + form, shinyBit * 2 + 0xBE + form)
  elseif speciesId == speciesIds["ARCEUS"] then
    return otherpoke(halfFacing + 0x60 + form * 2, shinyBit + 0xC2 + form * 2)
  elseif speciesId == speciesIds["CASTFORM"] then
    return otherpoke(facing * 2 + 0x40 + form, shinyBit * 4 + 0xA2 + form)
  elseif speciesId == speciesIds["DEOXYS"] then
    return otherpoke(halfFacing + form * 2, shinyBit + 0x9E)
  elseif speciesId == speciesIds["UNOWN"] then
    return otherpoke(halfFacing + 0x8 + form * 2, shinyBit + 0xA0)
  elseif speciesId == speciesIds["EGG"] then
    return otherpoke(0x84 + form, 0xE6 + form)
  elseif speciesId == speciesIds["BAD_EGG"] then
    return otherpoke(0x84, 0xE6)
  elseif speciesId == speciesIds["SHAYMIN"] then
    return otherpoke(halfFacing + 0x86 + form * 2, shinyBit + 0xE8 + form * 2)
  elseif speciesId == speciesIds["ROTOM"] then
    return otherpoke(halfFacing + 0x8A + form * 2, shinyBit + 0xEC + form * 2)
  elseif speciesId == speciesIds["GIRATINA"] then
    return otherpoke(halfFacing + 0x96 + form * 2, shinyBit + 0xF8 + form * 2)
  elseif speciesId == speciesIds["PICHU"] then
    return otherpoke(halfFacing + 0x9A + form * 2, shinyBit + 0xFC + form * 2)
  end
  return {
    narc = "pokemon_graphics",
    charMemberId = speciesId * 6 + facing + (isFemale and 0 or 1),
    palMemberId = shinyBit + speciesId * 6 + 4,
  }
end

-- Follower model-offset lookup ported from SpeciesToOverworldModelIndexOffset
-- (src/follow_mon.c). Species outside 0..493 have no follower model.
function MonSources.followerModelOffset(speciesId)
  if speciesId == nil or speciesId < 0 or speciesId > MonSources.MAX_SPECIES then
    return nil
  end
  return MonSources.followerModelOffsets[speciesId]
end

-- Follower sprite selection ported from FollowMon_GetSpriteID
-- (src/follow_mon.c). isFemale selects the female model where the source
-- female flag LUT provides one; otherwise the clamped form offset applies.
-- Returns nil for identities without a follower model.
function MonSources.followerSpriteId(speciesId, form, isFemale)
  local offset = MonSources.followerModelOffset(speciesId)
  if offset == nil then
    return nil
  end
  local spriteId
  if MonSources.followerFemaleFlags[speciesId] == true and isFemale then
    spriteId = MonSources.FOLLOWER_SPRITE_BASE + offset + 1
  else
    local formCount = 0
    if speciesId >= 1 then
      formCount = MonSources.followerFormCounts[speciesId] or 0
    end
    if form > formCount then
      form = 0
    end
    spriteId = MonSources.FOLLOWER_SPRITE_BASE + offset + form
  end
  if spriteId > MonSources.FOLLOWER_SPRITE_MAX then
    return MonSources.FOLLOWER_SPRITE_BASE
  end
  return spriteId
end

-- Follower tp_param member index: the model offset plus the same female/form
-- adjustment the sprite selection applies (src/follow_mon.c
-- FollowMon_SetObjectForm/FieldSystem_UnkSub108 readers).
function MonSources.followerParamIndex(speciesId, form, isFemale)
  local offset = MonSources.followerModelOffset(speciesId)
  if offset == nil then
    return nil
  end
  if MonSources.followerFemaleFlags[speciesId] == true and isFemale then
    return offset + 1
  end
  local formCount = 0
  if speciesId >= 1 then
    formCount = MonSources.followerFormCounts[speciesId] or 0
  end
  if form > formCount then
    form = 0
  end
  return offset + form
end

-- Deterministic runtime visual ID for a follower model offset. The source
-- sprite namespace (428..993) can collide with map actor IDs, so runtime
-- visuals live in the documented follower range instead.
function MonSources.followerVisualId(paramIndex)
  assert(type(paramIndex) == "number" and paramIndex >= 0, "follower param index required")
  return MonSources.FOLLOWER_VISUAL_ID_BASE + paramIndex
end

